describe("writeManifest", () => {
	it("replaces existing markers in rfc.md", () => {
		const rfcDir = makeRfc("demo", { "01-summary.md": "## 1. Summary\n\nHello\n" });
		writeManifest(rfcDir);
		const content = readFileSync(path.join(rfcDir, "rfc.md"), "utf8");
		expect(content).toContain("| 1 | Summary |");
	});

	it("appends markers when they are absent", () => {
		const rfcDir = makeRfc("demo", { "01-summary.md": "## 1. Summary\n\nHello\n" });
		// Strip markers from rfc.md
		const rfcMdPath = path.join(rfcDir, "rfc.md");
		const content = readFileSync(rfcMdPath, "utf8");
		const stripped = content
			.replace(/<!-- rfc:manifest:begin[\s\S]*?<!-- rfc:manifest:end -->/g, "")
			.trimEnd() + "\n";
		writeFileSync(rfcMdPath, stripped);
		expect(readFileSync(rfcMdPath, "utf8")).not.toContain("rfc:manifest");

		writeManifest(rfcDir);
		const updated = readFileSync(rfcMdPath, "utf8");
		expect(updated).toContain("<!-- rfc:manifest:begin");
		expect(updated).toContain("<!-- rfc:manifest:end -->");
		expect(updated).toContain("| 1 | Summary |");
	});
});


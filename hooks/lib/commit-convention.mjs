import { readdirSync, existsSync } from 'fs'
import { execFileSync } from 'child_process'
import { join } from 'path'

export const COMMIT_TYPES = [
  'feat', 'fix', 'docs', 'style', 'refactor',
  'perf', 'test', 'build', 'ci', 'chore', 'revert',
]

export const SCOPE_PATTERN = /^[a-zA-Z0-9._,\-]+$/

export const SUBJECT_CAP = 72

export const BODY_MAX_LINES = 0

export const ATTRIBUTION_TRAILER_PATTERNS = [
  /^Co-Authored-By:.*(?:Claude|Anthropic|claude\.ai|anthropic\.com).*$/im,
  /^Claude-Session:.*$/im,
  /^Generated with Claude Code.*$/im,
]

export const PROCESS_VOCAB_DENYLIST = [
  { pattern: /gate cycle/i,       label: 'process vocabulary: "gate cycle"' },
  { pattern: /dogfood cleanup/i,  label: 'process vocabulary: "dogfood cleanup"' },
  { pattern: /advisor APPROVE/i,  label: 'process vocabulary: "advisor APPROVE"' },
  { pattern: /\bT\d+\b/,         label: 'process vocabulary: slice id (e.g. T4)' },
  { pattern: /\bD-\d+\b/,        label: 'process vocabulary: decision id (e.g. D-7)' },
]

export function resolveRepoRoot(cwd) {
  try {
    return execFileSync('git', ['rev-parse', '--show-toplevel'], {
      cwd: cwd ?? process.cwd(),
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim() || null
  } catch {
    return null
  }
}

export function hasOwnCommitTemplate(repoRoot) {
  if (typeof repoRoot !== 'string' || repoRoot === '') return false
  return existsSync(join(repoRoot, '.gitmessage'))
}

export function getMotiveSlugs(repoRoot) {
  try {
    const root = repoRoot ?? resolveRepoRoot()
    return readdirSync(join(root, '.groundwork', 'motives'), { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
  } catch {
    return []
  }
}

export function lintMessage(text, opts) {
  let stripped = text
  for (const pattern of ATTRIBUTION_TRAILER_PATTERNS) {
    stripped = stripped.replace(
      new RegExp(pattern.source, pattern.flags.includes('g') ? pattern.flags : pattern.flags + 'g'),
      '',
    )
  }
  stripped = stripped.replace(/\n+$/, '').trimEnd()

  const violations = []
  const lines = stripped.split('\n')
  const subject = lines[0] ?? ''
  const isAutoGenerated = /^\(fixup|squash\)! /i.test(subject)

  // A repo shipping its own .gitmessage has declared its convention in the
  // canonical place; groundwork's format/length/body rules must not override it.
  const hostConvention = opts?.hostConvention === true

  if (!isAutoGenerated && !hostConvention) {
    const typesJoined = COMMIT_TYPES.join('|')
    const subjectRe = new RegExp(`^(${typesJoined})(\\([a-zA-Z0-9._,\\-]+\\))?!?: .+$`)

    if (!subjectRe.test(subject)) {
      violations.push({
        line: 1,
        reason: `subject must match type(scope)!: description — allowed types: ${COMMIT_TYPES.join(', ')}`,
      })
    } else {
      const afterColon = subject.replace(/^(?:[a-zA-Z]+)(?:\([^)]+\))?!?: /, '')
      if (afterColon.length > SUBJECT_CAP) {
        violations.push({
          line: 1,
          reason: `subject text is ${afterColon.length} characters; limit is ${SUBJECT_CAP}`,
        })
      }
    }
  }

  if (!hostConvention && lines.length > 1 && lines[1] !== '') {
    violations.push({
      line: 2,
      reason: 'line 2 must be blank (the separator between subject and body)',
    })
  }

  if (!hostConvention && lines.length > 2) {
    const bodyLines = lines.slice(2)
    const nonBlankBody = bodyLines.filter((l) => l.trim() !== '')

    if (nonBlankBody.length > BODY_MAX_LINES) {
      violations.push({
        line: 3,
        reason: `body has ${nonBlankBody.length} non-blank lines; limit is ${BODY_MAX_LINES}`,
      })
    }

    bodyLines.forEach((bodyLine, idx) => {
      if (/^\s*[-*•]\s/.test(bodyLine)) {
        violations.push({
          line: 3 + idx,
          reason: 'body lines must not use bullet markers (-, *, •); write plain prose',
        })
      }
    })
  }

  lines.forEach((line, idx) => {
    for (const { pattern, label } of PROCESS_VOCAB_DENYLIST) {
      if (pattern.test(line)) {
        violations.push({ line: idx + 1, reason: `contains ${label}` })
      }
    }
  })

  const slugs = opts?.motiveSlugs ?? getMotiveSlugs()
  if (slugs.length > 0) {
    lines.forEach((line, idx) => {
      for (const slug of slugs) {
        const escaped = slug.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
        if (new RegExp(`\\b${escaped}\\b`).test(line)) {
          violations.push({
            line: idx + 1,
            reason: `contains motive slug "${slug}" — process vocabulary not for commit messages`,
          })
        }
      }
    })
  }

  return { stripped, violations }
}

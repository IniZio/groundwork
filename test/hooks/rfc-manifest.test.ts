describe("manifest section ordering — correctness", () => {
	it("top-level directory sections appear §1 before §2 before §3 (M6)", () => {
		// Uses directory sections so the sort at ~line 448 is exercised.
		// If reversed, §3 would appear first; indexOf comparisons catch it.
		const rfcDir = makeRfc("order-top-level", {
			"03-conclusion/01-final.md": "## Final\n\nConclusion.\n",
			"01-overview/01-intro.md": "## Intro\n\nOverview.\n",
			"02-analysis/01-detail.md": "## Detail\n\nAnalysis.\n",
		});
		const block = generateManifestBlock(rfcDir)!;
		const idx1 = block.indexOf("| 1 |");
		const idx2 = block.indexOf("| 2 |");
		const idx3 = block.indexOf("| 3 |");
		expect(idx1).toBeGreaterThanOrEqual(0);
		expect(idx2).toBeGreaterThanOrEqual(0);
		expect(idx3).toBeGreaterThanOrEqual(0);
		expect(idx1).toBeLessThan(idx2);
		expect(idx2).toBeLessThan(idx3);
	});

	it("child file rows within a directory appear §N.1 before §N.2 before §N.3 (M7)", () => {
		// Uses a directory with multiple children so the child sort at ~line 470 is exercised.
		// If reversed, §1.3 would appear first; indexOf comparisons catch it.
		const rfcDir = makeRfc("order-child-level", {
			"01-overview/03-third.md": "## Third\n\nThird child.\n",
			"01-overview/01-first.md": "## First\n\nFirst child.\n",
			"01-overview/02-second.md": "## Second\n\nSecond child.\n",
		});
		const block = generateManifestBlock(rfcDir)!;
		const idx11 = block.indexOf("| 1.1 |");
		const idx12 = block.indexOf("| 1.2 |");
		const idx13 = block.indexOf("| 1.3 |");
		expect(idx11).toBeGreaterThanOrEqual(0);
		expect(idx12).toBeGreaterThanOrEqual(0);
		expect(idx13).toBeGreaterThanOrEqual(0);
		expect(idx11).toBeLessThan(idx12);
		expect(idx12).toBeLessThan(idx13);
	});
});

// ---------------------------------------------------------------------------
// Digest invariance: manifest does NOT affect computeBodyDigest
// ---------------------------------------------------------------------------

describe("body_digest invariance", () => {
	it("computeBodyDigest returns the same value before and after writing the manifest", async () => {
		const { computeBodyDigest, parseFrontmatter, generateManifestBlock, writeManifest } =
			await import("../../hooks/lib/rfc-io.mjs");

		const rfcDir = createRfc("digest-invariance");
		const content1 = readFileSync(path.join(rfcDir, "rfc.md"), "utf8");
		const { frontmatter: fm1 } = parseFrontmatter(content1);
		const digest1 = computeBodyDigest(fm1, rfcDir);

		// Corrupt manifest and then regenerate — digest must not change
		const rfcMdPath = path.join(rfcDir, "rfc.md");
		writeFileSync(rfcMdPath, content1.replace(/<!-- rfc:manifest:end -->/, "<!-- rfc:manifest:end -->\nEXTRA LINE"));
		writeManifest(rfcDir);

		const content2 = readFileSync(rfcMdPath, "utf8");
		const { frontmatter: fm2 } = parseFrontmatter(content2);
		const digest2 = computeBodyDigest(fm2, rfcDir);

		expect(digest1).toBe(digest2);
	});
});

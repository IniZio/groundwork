import { describe, it, expect, afterAll } from 'bun:test';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';

const BIN = path.resolve(import.meta.dir, '../../bin/house-rules');
const dirs: string[] = [];

function childEnv(): NodeJS.ProcessEnv {
  const env = { ...process.env };
  delete env.CLAUDE_PROJECT_DIR;
  return env;
}

function makeRepo(files: Record<string, string>, config?: object): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'hr-generated-'));
  dirs.push(dir);
  spawnSync('git', ['init', '-b', 'main', dir], { encoding: 'utf8' });
  spawnSync('git', ['-C', dir, 'config', 'user.email', 'test@example.com'], { encoding: 'utf8' });
  spawnSync('git', ['-C', dir, 'config', 'user.name', 'Test User'], { encoding: 'utf8' });
  if (config !== undefined) files['.house-rules.json'] = JSON.stringify(config);
  for (const [rel, text] of Object.entries(files)) {
    const abs = path.join(dir, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, text, 'utf8');
  }
  spawnSync('git', ['-C', dir, 'add', '-A'], { encoding: 'utf8' });
  spawnSync('git', ['-C', dir, 'commit', '-m', 'init'], { encoding: 'utf8' });
  return dir;
}

interface Row { ruleId: string; path: string; line?: number; severity?: string }

function check(dir: string): { rows: Row[]; status: number | null } {
  const r = spawnSync(BIN, ['check', '--all', '--format', 'json'], { cwd: dir, encoding: 'utf8', env: childEnv() });
  const parsed = JSON.parse(r.stdout) as { findings?: Row[] } | Row[];
  return { rows: Array.isArray(parsed) ? parsed : parsed.findings ?? [], status: r.status };
}

afterAll(() => {
  for (const d of dirs) fs.rmSync(d, { recursive: true, force: true });
});

const COMMENTS = ['// one', '// two', '// three', '// four', '// five', '// six'];
const DENSE = [...COMMENTS, 'export const a = 1;', '', 'export const b = 2;', '', 'export const c = 3;', ''].join('\n') + '\n';
const MARKED = '// @generated by tool\n' + DENSE;

describe('generated and vendored files are skipped by content rules', () => {
  it('unmarked file reports comment-density; marked file reports nothing', () => {
    const dir = makeRepo({ 'src/plain.ts': DENSE, 'src/gen.ts': MARKED });
    const { rows, status } = check(dir);
    expect(rows.some((f) => f.ruleId === 'comment-density' && f.path === 'src/plain.ts')).toBe(true);
    expect(rows.filter((f) => f.path === 'src/gen.ts')).toEqual([]);
    expect(status).not.toBe(0);
  });

  it('linguist-vendored path reports nothing; unmarked twin reports', () => {
    const dir = makeRepo({
      '.gitattributes': 'vendor/** linguist-vendored\n',
      'vendor/lib.ts': DENSE,
      'src/lib.ts': DENSE,
    });
    const { rows } = check(dir);
    expect(rows.filter((f) => f.path === 'vendor/lib.ts')).toEqual([]);
    expect(rows.some((f) => f.ruleId === 'comment-density' && f.path === 'src/lib.ts')).toBe(true);
  });

  it('artifact-structure still reports a generated root scratch file', () => {
    const dir = makeRepo({ 'tmp-x.ts': MARKED });
    const { rows } = check(dir);
    expect(rows.some((f) => f.ruleId === 'artifact-structure' && f.path === 'tmp-x.ts')).toBe(true);
    expect(rows.filter((f) => f.path === 'tmp-x.ts' && f.ruleId !== 'artifact-structure')).toEqual([]);
  });
});

describe('safety comment rule overlap with type-escape-hatches', () => {
  const SRC = [
    'export const chained = (x: Bar) => x as unknown as Foo;',
    'export const single = foo() as Foo;',
    '',
  ].join('\n');
  const config = { rules: { 'require-safety-comment-for-type-assertion': 'warn' } };

  it('chained assertion is reported once by type-escape-hatches; single by safety', () => {
    const dir = makeRepo({ 'src/a.ts': SRC }, config);
    const { rows } = check(dir);
    const onChained = rows.filter((f) => f.path === 'src/a.ts' && f.line === 1);
    expect(onChained.map((f) => f.ruleId)).toEqual(['type-escape-hatches']);
    const onSingle = rows.filter((f) => f.path === 'src/a.ts' && f.line === 2);
    expect(onSingle.map((f) => f.ruleId)).toContain('require-safety-comment-for-type-assertion');
  });

  it('a test file is still checked by the safety rule', () => {
    const dir = makeRepo({ 'src/a.test.ts': SRC }, config);
    const { rows } = check(dir);
    expect(rows.some((f) => f.path === 'src/a.test.ts' && f.ruleId === 'require-safety-comment-for-type-assertion' && f.line === 2)).toBe(true);
  });
});

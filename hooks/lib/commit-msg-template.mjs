/**
 * commit-msg-template — portable commit-msg hook generator for host repositories.
 *
 * Usage (T32 auto-install / T33 gw-hooks CLI):
 *
 *   import { renderCommitMsgHook, HOOK_MARKER, isGroundworkHook } from './commit-msg-template.mjs'
 *   import { getHooksLibPath } from './groundwork-resolver.mjs'
 *
 *   const content = renderCommitMsgHook({ hooksLibPath: getHooksLibPath(), version: '3.1.0' })
 *   fs.writeFileSync(hookPath, content, { mode: 0o755 })
 *
 * Detecting our hook vs. a foreign hook (T32/T33 interface):
 *   - The marker line is always the second line: `# GROUNDWORK-COMMIT-MSG v<version>`
 *   - Use isGroundworkHook(content) to test portably.
 *   - Never overwrite a file that fails isGroundworkHook().
 */

/**
 * Stable marker string embedded in the second line of every generated hook.
 * Full marker line: `# GROUNDWORK-COMMIT-MSG v<version>`
 */
export const HOOK_MARKER = 'GROUNDWORK-COMMIT-MSG'

/**
 * Returns true iff the given file content was generated by groundwork.
 * Version-agnostic — checks only the marker prefix.
 *
 * @param {string} content  Raw content of a .git/hooks/commit-msg file
 */
export function isGroundworkHook(content) {
  return content.split('\n').some((line) => line.startsWith('# ' + HOOK_MARKER + ' v'))
}

/**
 * Render the portable commit-msg hook script for installation into a host repo.
 *
 * The generated script:
 *   - Embeds hooksLibPath at generation time (no runtime discovery needed)
 *   - FAIL SAFE: missing or unloadable groundwork → stderr warning + exit 0
 *   - Applies identical rules to groundwork's own hooks/commit-msg:
 *     strips attribution trailers, rejects other convention violations
 *   - Passthrough on GROUNDWORK_COMMIT_LINT=0
 *
 * @param {{ hooksLibPath: string, version: string }} opts
 * @returns {string} Complete hook file content (caller must set mode 0o755)
 */
export function renderCommitMsgHook({ hooksLibPath, version }) {
  // Build the Node.js script that runs inside the bash heredoc.
  // Uses double-quoted string concatenation (not template literals) so the
  // output contains bare backticks and ${} sequences without escaping fights.
  const nodeLines = [
    "import { readFileSync, writeFileSync, existsSync } from 'node:fs'",
    "",
    "const libPath = process.env.GROUNDWORK_HOOKS_LIB",
    "const convPath = `${libPath}/commit-convention.mjs`",
    "",
    "if (!libPath || !existsSync(convPath)) {",
    "  process.stderr.write(`commit-msg: groundwork not found at ${libPath ?? '(unset)'} — skipping lint\\n`)",
    "  process.exit(0)",
    "}",
    "",
    "let lintMessage",
    "try {",
    "  const mod = await import(`file://${convPath}`)",
    "  lintMessage = mod.lintMessage",
    "} catch (err) {",
    "  process.stderr.write(`commit-msg: failed to load groundwork (${err?.message ?? err}) — skipping lint\\n`)",
    "  process.exit(0)",
    "}",
    "",
    "const msgFile = process.env.COMMIT_MSG_FILE",
    "if (!msgFile) {",
    "  process.stderr.write('commit-msg: missing argument (commit message file path)\\n')",
    "  process.exit(1)",
    "}",
    "",
    "const commentChar = process.env.COMMENT_CHAR || '#'",
    "const cleanupMode = process.env.CLEANUP_MODE || 'default'",
    "const escapedChar = commentChar.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&')",
    "",
    "const original = readFileSync(msgFile, 'utf8')",
    "let cleaned = original",
    "",
    "if (cleanupMode === 'scissors') {",
    "  const idx = cleaned.search(new RegExp('^' + escapedChar + ' -{8,} >8 -{8,}$', 'm'))",
    "  if (idx !== -1) cleaned = cleaned.slice(0, idx)",
    "}",
    "",
    "cleaned = cleaned.replace(new RegExp('^' + escapedChar + '.*$', 'gm'), '')",
    "cleaned = cleaned.replace(/\\n{3,}/g, '\\n\\n')",
    "",
    "const { stripped, violations } = lintMessage(cleaned)",
    "",
    "writeFileSync(msgFile, stripped.trimEnd() + '\\n')",
    "",
    "if (violations.length > 0) {",
    "  for (const { line, reason } of violations) {",
    "    process.stderr.write(`commit-msg: line ${line}: ${reason}\\n`)",
    "  }",
    "  process.exit(1)",
    "}",
  ]

  const bashLines = [
    "#!/bin/bash",
    "# " + HOOK_MARKER + " v" + version,
    "# Managed by groundwork — do not edit.",
    "if [ \"${GROUNDWORK_COMMIT_LINT:-}\" = \"0\" ]; then exit 0; fi",
    "",
    "GROUNDWORK_HOOKS_LIB=\"" + hooksLibPath + "\"",
    "COMMENT_CHAR=\"$(git config --get core.commentChar 2>/dev/null || echo '#')\"",
    "CLEANUP_MODE=\"$(git config --get commit.cleanup 2>/dev/null || echo 'default')\"",
    "COMMIT_MSG_FILE=\"$1\" GROUNDWORK_HOOKS_LIB=\"$GROUNDWORK_HOOKS_LIB\" COMMENT_CHAR=\"$COMMENT_CHAR\" CLEANUP_MODE=\"$CLEANUP_MODE\" exec node --input-type=module <<'EOF'",
    ...nodeLines,
    "EOF",
    "",
  ]

  return bashLines.join('\n')
}

const FIXTURE_DIR = path.join(
  import.meta.dir,
  "../fixtures/comment-density/go-directives",
);
const CORPUS_FILE = path.join(FIXTURE_DIR, "corpus.go");
const REPO_ROOT = path.resolve(import.meta.dir, "../../../..");

// ─── helpers ────────────────────────────────────────────────────────────────

function mulberry32(seed: number): () => number {
  return function () {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

async function countErrorNodes(
  text: string,
): Promise<number> {
  const { getParser: gp } = await import(
    "../../src/hooks/lib/tree-sitter-loader.js"
  );
  const r = await gp("go");
  if (!r.ok) throw new Error(r.reason);
  const tree = r.parser.parse(text);
  let count = 0;
  function walk(node: import("../../src/hooks/lib/tree-sitter.js").Node): void {
    if (node.type === "ERROR") count++;
    for (let i = 0; i < node.childCount; i++) {
      const child = node.child(i);
      if (child) walk(child);
    }
  }
  walk(tree.rootNode);
  return count;
}

function codeTokens(text: string, comments: Comment[]): string {
  // Strip all comments, then normalize whitespace to compare code content.
  const { text: stripped } = stripComments(text, comments);
  return stripped.replace(/\s+/g, " ").trim();
}


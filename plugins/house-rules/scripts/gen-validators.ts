import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { Ajv, type AnySchema } from "ajv";
import standalone from "ajv/dist/standalone/index.js";
import { contentSchema, entrySchema } from "../src/hooks/lib/transcript-schemas.js";

const PLUGIN_ROOT = path.resolve(import.meta.dir, "..");
const SELF = "scripts/gen-validators.ts";

interface Validator {
  name: string;
  schema: AnySchema;
  /** The TS type the schema derives from, exported by `typesFrom`. */
  type: string;
}

interface ValidatorModule {
  /** Output path relative to the plugin root, without extension; `.mjs` and `.d.mts` are written. */
  out: string;
  /** Plugin-relative module that exports each schema and its type. */
  typesFrom: string;
  validators: Validator[];
}

const MODULES: ValidatorModule[] = [
  {
    out: "src/hooks/lib/generated/transcript-validators",
    typesFrom: "src/hooks/lib/transcript-schemas.ts",
    validators: [
      { name: "isEntry", schema: entrySchema, type: "RawEntry" },
      { name: "hasBlocks", schema: contentSchema, type: "RawContent" },
    ],
  },
];

function header(mod: ValidatorModule): string {
  return `// Generated by ${SELF} from ${mod.typesFrom}; edit the schema and rerun it.\n`;
}

function renderCode(mod: ValidatorModule): string {
  const ajv = new Ajv({ code: { source: true, esm: true } });
  const refs: Record<string, string> = {};
  for (const v of mod.validators) {
    ajv.addSchema(v.schema, v.name);
    refs[v.name] = v.name;
  }
  const code = standalone.default(ajv, refs);
  if (/\brequire\(|^\s*import\b/m.test(code)) {
    throw new Error(`${mod.out}: standalone code needs an ajv runtime helper; change the schema to avoid it`);
  }
  return header(mod) + code + "\n";
}

function renderTypes(mod: ValidatorModule): string {
  const fromDir = path.dirname(mod.out);
  const rel = path.relative(fromDir, mod.typesFrom).replace(/\.ts$/, ".js");
  const spec = rel.startsWith("..") ? rel : `./${rel}`;
  const types = [...new Set(mod.validators.map((v) => v.type))].sort();
  const lines = [header(mod) + `import type { ${types.join(", ")} } from "${spec}";`, ""];
  for (const v of mod.validators) {
    lines.push(`export declare function ${v.name}(data: unknown): data is ${v.type};`);
  }
  return lines.join("\n") + "\n";
}

/** Every generated file, keyed by plugin-relative path. */
export function renderAll(): Map<string, string> {
  const files = new Map<string, string>();
  for (const mod of MODULES) {
    files.set(`${mod.out}.mjs`, renderCode(mod));
    files.set(`${mod.out}.d.mts`, renderTypes(mod));
  }
  return files;
}

/** Plugin-relative paths under `root` whose content differs from a fresh render. */
export function staleFiles(root: string): string[] {
  const stale: string[] = [];
  for (const [rel, text] of renderAll()) {
    const file = path.join(root, rel);
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) stale.push(rel);
  }
  return stale;
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const stale = staleFiles(PLUGIN_ROOT);
    for (const rel of stale) console.error(`stale: ${rel} (run bun plugins/house-rules/${SELF})`);
    if (stale.length > 0) process.exit(1);
    console.log(`validators checked: ${renderAll().size}`);
  } else {
    for (const [rel, text] of renderAll()) {
      const file = path.join(PLUGIN_ROOT, rel);
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
      console.log(`wrote ${rel}`);
    }
  }
}

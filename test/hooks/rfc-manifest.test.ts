describe("extractManifestBlock", () => {
	it("returns null when markers are absent", () => {
		expect(extractManifestBlock("no markers here")).toBeNull();
	});

	it("returns the block including begin and end markers", () => {
		const content = "preamble\n<!-- rfc:manifest:begin — generated by `rfc index`; do not hand-edit -->\n| § | Title | File | Tokens |\ntable row\n<!-- rfc:manifest:end -->\npostamble";
		const block = extractManifestBlock(content)!;
		expect(block).toMatch(/^<!-- rfc:manifest:begin/);
		expect(block).toMatch(/<!-- rfc:manifest:end -->$/);
		expect(block).toContain("table row");
		expect(block).not.toContain("preamble");
		expect(block).not.toContain("postamble");
	});
});


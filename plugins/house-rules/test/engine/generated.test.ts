import { describe, it, expect } from 'bun:test';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { isGeneratedText, generatedPaths } from '../../src/engine/generated.js';

const PLUGIN_ROOT = resolve(import.meta.dir, '../..');
const REPO_ROOT = resolve(PLUGIN_ROOT, '../..');

const GO_HEADER_FIXTURE = 'go-directives/corpus.go';

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === '.git') continue;
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) walk(p, out);
    else if (st.size < 2_000_000) out.push(p);
  }
  return out;
}

function git(cwd: string, ...args: string[]): void {
  const r = spawnSync('git', args, { cwd, encoding: 'utf8' });
  if (r.status !== 0) throw new Error(r.stderr);
}

function tmpRepo(): string {
  const dir = mkdtempSync(join(tmpdir(), 'generated-'));
  git(dir, 'init', '-q');
  return dir;
}

describe('isGeneratedText', () => {
  it('detects @generated in a leading line comment', () => {
    expect(isGeneratedText('// @generated\nconst a = 1;\n')).toBe(true);
  });
  it('detects Go code-generated header', () => {
    expect(isGeneratedText('// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n')).toBe(true);
  });
  it('detects marker in block, hash, and html comments', () => {
    expect(isGeneratedText('/*\n * DO NOT EDIT\n */\nx')).toBe(true);
    expect(isGeneratedText('# @generated by tool\nx = 1\n')).toBe(true);
    expect(isGeneratedText('<!-- DO NOT EDIT -->\n<p/>')).toBe(true);
  });
  it('detects marker on line 5', () => {
    expect(isGeneratedText('// a\n// b\n// c\n// d\n// @generated\nx')).toBe(true);
  });
  it('ignores marker below line 5', () => {
    expect(isGeneratedText('// a\n// b\n// c\n// d\n// e\n// @generated\nx')).toBe(false);
  });
  it('ignores marker inside a string literal', () => {
    expect(isGeneratedText("const s = '// @generated';\n")).toBe(false);
    expect(isGeneratedText('const s = "DO NOT EDIT";\n')).toBe(false);
  });
  it('is false for plain text', () => {
    expect(isGeneratedText('')).toBe(false);
    expect(isGeneratedText('export const a = 1;\n')).toBe(false);
  });
  it('is false for every real repo file that mentions the markers', () => {
    const hits = walk(PLUGIN_ROOT).filter((p) => !p.endsWith(GO_HEADER_FIXTURE)).filter((p) => {
      const t = readFileSync(p, 'utf8');
      return t.includes('@generated') || t.includes('DO NOT EDIT');
    });
    expect(hits.length).toBeGreaterThan(5);
    for (const p of hits) expect([p, isGeneratedText(readFileSync(p, 'utf8'))]).toEqual([p, false]);
  });
});

it('treats the Go fixture with a real generated header on line 4 as generated', () => {
  expect(isGeneratedText(readFileSync(join(PLUGIN_ROOT, 'test/fixtures/comment-density/' + GO_HEADER_FIXTURE), 'utf8'))).toBe(true);
});

describe('generatedPaths', () => {
  it('marks linguist-generated and linguist-vendored, honours unset', () => {
    const dir = tmpRepo();
    writeFileSync(join(dir, '.gitattributes'), 'gen.ts linguist-generated\nvend/** linguist-vendored\nvend/own.ts -linguist-vendored\nlib.ts linguist-generated=false\n');
    mkdirSync(join(dir, 'vend'));
    const paths = ['gen.ts', 'vend/a.ts', 'vend/own.ts', 'lib.ts', 'plain.ts'];
    expect([...generatedPaths(dir, paths)].sort()).toEqual(['gen.ts', 'vend/a.ts']);
  });
  it('returns empty outside a git repo', () => {
    const dir = mkdtempSync(join(tmpdir(), 'nogit-'));
    expect(generatedPaths(dir, ['a.ts']).size).toBe(0);
  });
  it('returns empty for no paths', () => {
    expect(generatedPaths(tmpRepo(), []).size).toBe(0);
  });
  it('real repo root reports vendored tree-sitter', () => {
    const p = 'plugins/house-rules/src/hooks/lib/tree-sitter.js';
    const got = generatedPaths(REPO_ROOT, [p, 'plugins/house-rules/src/engine/run.ts']);
    expect([...got]).toEqual([p]);
  });
});

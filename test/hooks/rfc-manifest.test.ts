describe("generateManifestBlock", () => {
	it("returns null when sections/ does not exist", () => {
		const dir = mkdtempSync(path.join(tmpdir(), "gw-mfst-"));
		try {
			expect(generateManifestBlock(dir)).toBeNull();
		} finally {
			rmSync(dir, { recursive: true, force: true });
		}
	});

	it("generates begin/end markers", () => {
		const rfcDir = makeRfc("demo", { "01-summary.md": "## 1. Summary\n\nHello\n" });
		const block = generateManifestBlock(rfcDir)!;
		expect(block).toContain("<!-- rfc:manifest:begin");
		expect(block).toContain("<!-- rfc:manifest:end -->");
	});

	it("generates a row for each numbered file", () => {
		const rfcDir = makeRfc("demo", {
			"01-summary.md": "## 1. Summary\n\nHello\n",
			"02-motivation.md": "## 2. Motivation\n\nWorld\n",
		});
		const block = generateManifestBlock(rfcDir)!;
		expect(block).toContain("| 1 | Summary |");
		expect(block).toContain("| 2 | Motivation |");
	});

	it("generates directory aggregate row + child rows", () => {
		const rfcDir = makeRfc("demo", {
			"01-overview/01-intro.md": "## Intro\n\nHi\n",
			"01-overview/02-detail.md": "## Detail\n\nDetails\n",
		});
		const block = generateManifestBlock(rfcDir)!;
		// Directory aggregate row
		expect(block).toMatch(/\| 1 \| Overview \| sections\/01-overview\/ \|/);
		// Child rows
		expect(block).toMatch(/\| 1\.1 \| Intro \| sections\/01-overview\/01-intro\.md \|/);
		expect(block).toMatch(/\| 1\.2 \| Detail \| sections\/01-overview\/02-detail\.md \|/);
	});

	it("_intro.md is NOT listed as a separate row", () => {
		const rfcDir = makeRfc("demo", {
			"01-overview/_intro.md": "Overview intro text\n",
			"01-overview/01-detail.md": "## Detail\n\nFoo\n",
		});
		const block = generateManifestBlock(rfcDir)!;
		expect(block).not.toContain("_intro");
	});

	it("token count uses Math.ceil(bytes / 3.5) — not Math.floor", () => {
		// 4 bytes → Math.ceil(4/3.5) = Math.ceil(1.142...) = 2
		//          → Math.floor(4/3.5) = Math.floor(1.142...) = 1  ← distinguishes ceil vs floor
		const rfcDir = makeRfc("demo", { "01-summary.md": "ABCD" }); // exactly 4 bytes
		const block = generateManifestBlock(rfcDir)!;
		expect(block).toContain("| 1 | Summary | sections/01-summary.md | 2 |");
	});

	it("slugToTitle: converts kebab-slug to sentence-case", () => {
		const rfcDir = makeRfc("demo", { "01-full-layout.md": "x" });
		const block = generateManifestBlock(rfcDir)!;
		expect(block).toContain("| 1 | Full layout |");
	});

	it("sections appear in ascending numeric order", () => {
		const rfcDir = makeRfc("demo", {
			"03-design.md": "design",
			"01-summary.md": "summary",
			"02-motivation.md": "motivation",
		});
		const block = generateManifestBlock(rfcDir)!;
		const lines = block.split("\n");
		const nums = lines
			.filter((l) => l.startsWith("| ") && !l.startsWith("| §"))
			.map((l) => parseInt(l.split("|")[1].trim()));
		expect(nums).toEqual([1, 2, 3]);
	});
});


import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { Ajv, type AnySchema } from "ajv";
import standalone from "ajv/dist/standalone/index.js";
import { manifestSchema } from "../src/engine/project-deps-schemas.js";
import {
  backgroundTaskSchema, booleanSchema, editsSchema, jsonObjectSchema, stringSchema,
} from "../src/hooks/lib/hook-input-schemas.js";
import { contentSchema, entrySchema } from "../src/hooks/lib/transcript-schemas.js";

const PLUGIN_ROOT = path.resolve(import.meta.dir, "..");
const SELF = "scripts/gen-validators.ts";

export interface Validator {
  name: string;
  schema: AnySchema;
  /** The TS type the schema derives from, exported by `typesFrom`. */
  type: string;
}

export interface ValidatorModule {
  /** Output path relative to the root that owns the generator script, without extension; `.mjs` and `.d.mts` are written. */
  out: string;
  /** Root-relative module that exports each schema and its type. */
  typesFrom: string;
  validators: Validator[];
}

const MODULES: ValidatorModule[] = [
  {
    out: "src/hooks/lib/generated/transcript-validators",
    typesFrom: "src/hooks/lib/transcript-schemas.ts",
    validators: [
      { name: "isEntry", schema: entrySchema, type: "RawEntry" },
      { name: "hasBlocks", schema: contentSchema, type: "RawContent" },
    ],
  },
  {
    out: "src/hooks/lib/generated/hook-input-validators",
    typesFrom: "src/hooks/lib/hook-input-schemas.ts",
    validators: [
      { name: "hasJsonObject", schema: jsonObjectSchema, type: "JsonObject" },
      { name: "hasString", schema: stringSchema, type: "JsonString" },
      { name: "hasBoolean", schema: booleanSchema, type: "JsonBoolean" },
      { name: "hasBackgroundTask", schema: backgroundTaskSchema, type: "BackgroundTask" },
      { name: "hasEdits", schema: editsSchema, type: "Edits" },
    ],
  },
  {
    out: "src/engine/generated/project-deps-validators",
    typesFrom: "src/engine/project-deps-schemas.ts",
    validators: [{ name: "isManifest", schema: manifestSchema, type: "Manifest" }],
  },
];

function header(mod: ValidatorModule, self: string): string {
  return `// Generated by ${self} from ${mod.typesFrom}; edit the schema and rerun it.\n`;
}

function renderCode(mod: ValidatorModule, self: string): string {
  const ajv = new Ajv({ code: { source: true, esm: true } });
  const refs: Record<string, string> = {};
  for (const v of mod.validators) {
    ajv.addSchema(v.schema, v.name);
    refs[v.name] = v.name;
  }
  const code = standalone.default(ajv, refs);
  if (/\brequire\(|^\s*import\b/m.test(code)) {
    throw new Error(`${mod.out}: standalone code needs an ajv runtime helper; change the schema to avoid it`);
  }
  return header(mod, self) + code + "\n";
}

function renderTypes(mod: ValidatorModule, self: string): string {
  const fromDir = path.dirname(mod.out);
  const rel = path.relative(fromDir, mod.typesFrom).replace(/\.ts$/, ".js");
  const spec = rel.startsWith("..") ? rel : `./${rel}`;
  const types = [...new Set(mod.validators.map((v) => v.type.replace(/\[\]$/, "")))].sort();
  const lines = [header(mod, self) + `import type { ${types.join(", ")} } from "${spec}";`, ""];
  for (const v of mod.validators) {
    lines.push(`export declare function ${v.name}(data: unknown): data is ${v.type};`);
  }
  return lines.join("\n") + "\n";
}

/** Every file the given modules generate, keyed by root-relative path; `self` is the script named in the header. */
export function renderModules(modules: ValidatorModule[], self: string): Map<string, string> {
  const files = new Map<string, string>();
  for (const mod of modules) {
    files.set(`${mod.out}.mjs`, renderCode(mod, self));
    files.set(`${mod.out}.d.mts`, renderTypes(mod, self));
  }
  return files;
}

/** Root-relative paths under `root` whose content differs from `files`. */
export function staleIn(root: string, files: Map<string, string>): string[] {
  const stale: string[] = [];
  for (const [rel, text] of files) {
    const file = path.join(root, rel);
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) stale.push(rel);
  }
  return stale;
}

/** Every generated file, keyed by plugin-relative path. */
export function renderAll(): Map<string, string> {
  return renderModules(MODULES, SELF);
}

/** Plugin-relative paths under `root` whose content differs from a fresh render. */
export function staleFiles(root: string): string[] {
  return staleIn(root, renderAll());
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const stale = staleFiles(PLUGIN_ROOT);
    for (const rel of stale) console.error(`stale: ${rel} (run bun plugins/house-rules/${SELF})`);
    if (stale.length > 0) process.exit(1);
    console.log(`validators checked: ${renderAll().size}`);
  } else {
    for (const [rel, text] of renderAll()) {
      const file = path.join(PLUGIN_ROOT, rel);
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
      console.log(`wrote ${rel}`);
    }
  }
}

describe("_intro.md exclusion from manifest — correctness", () => {
	it("top-level sections/_intro.md is NOT included as a manifest row (M4)", () => {
		// _intro.md placed directly inside sections/ — exercises the top-level loop guard
		// at ~line 439. If the guard is mutated (e.g. condition negated), 01-summary.md
		// would be skipped instead, producing zero data rows.
		const rfcDir = makeRfc("intro-top-level", {
			"_intro.md": "Top-level intro stub.\n",
			"01-summary.md": "## Summary\n\nContent here.\n",
		});
		const block = generateManifestBlock(rfcDir)!;
		expect(block).not.toContain("_intro");
		// Exactly one data row — §1 for 01-summary.md only
		const dataRows = block.split("\n").filter((l) => /^\| \d/.test(l));
		expect(dataRows).toHaveLength(1);
		expect(dataRows[0]).toMatch(/^\| 1 \|/);
	});

	it("child-level sections/NN-dir/_intro.md is NOT included as a child row (M8)", () => {
		// _intro.md inside a numbered subdirectory — exercises the child loop guard
		// at ~line 464. If mutated, the manifest would gain a bogus child row for _intro.md.
		const rfcDir = makeRfc("intro-child-level", {
			"01-overview/_intro.md": "Overview intro stub.\n",
			"01-overview/01-detail.md": "## Detail\n\nContent here.\n",
			"01-overview/02-more.md": "## More\n\nExtra content.\n",
		});
		const block = generateManifestBlock(rfcDir)!;
		expect(block).not.toContain("_intro");
		// Exactly three data rows: §1 (dir aggregate), §1.1, §1.2 — NOT four
		const dataRows = block.split("\n").filter((l) => /^\| \d/.test(l));
		expect(dataRows).toHaveLength(3);
		expect(dataRows[0]).toMatch(/^\| 1 \|.*sections\/01-overview\//);
		expect(dataRows[1]).toMatch(/^\| 1\.1 \|/);
		expect(dataRows[2]).toMatch(/^\| 1\.2 \|/);
	});
});


import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { Ajv } from "ajv";
import standalone from "ajv/dist/standalone/index.js";
import { entrySchema, hookInputSchema } from "../src/hooks/lib/transcript-schemas.js";

const ROOT = path.resolve(import.meta.dir, "..");
const SELF = "scripts/gen-validators.ts";
const OUT = "src/hooks/lib/generated/transcript-validators";
const HEADER = `// Generated by ${SELF} from src/hooks/lib/transcript-schemas.ts; edit the schema and rerun it.\n`;

const VALIDATORS = [
  { name: "isTranscriptEntry", schema: entrySchema, type: "TranscriptEntry" },
  { name: "isHookInput", schema: hookInputSchema, type: "HookInput" },
];

function render(): Map<string, string> {
  const ajv = new Ajv({ code: { source: true, esm: true } });
  const refs: Record<string, string> = {};
  for (const v of VALIDATORS) {
    ajv.addSchema(v.schema, v.name);
    refs[v.name] = v.name;
  }
  const source = standalone.default(ajv, refs);
  if (/\brequire\(|^\s*import\b/m.test(source)) throw new Error("standalone code needs an ajv runtime helper; change the schema to avoid it");
  const types = VALIDATORS.map((v) => v.type).sort().join(", ");
  const dts = [
    `${HEADER}import type { ${types} } from "../transcript-schemas.js";`,
    "",
    ...VALIDATORS.map((v) => `export declare function ${v.name}(data: unknown): data is ${v.type};`),
  ].join("\n") + "\n";
  return new Map([[`${OUT}.mjs`, HEADER + source + "\n"], [`${OUT}.d.mts`, dts]]);
}

const files = render();
if (process.argv.includes("--check")) {
  const stale = [...files].filter(([rel, text]) => !fs.existsSync(path.join(ROOT, rel)) || fs.readFileSync(path.join(ROOT, rel), "utf8") !== text);
  for (const [rel] of stale) console.error(`stale: ${rel} (run bun ${SELF})`);
  process.exit(stale.length > 0 ? 1 : 0);
}
for (const [rel, text] of files) {
  fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, rel), text);
  console.log(`wrote ${rel}`);
}

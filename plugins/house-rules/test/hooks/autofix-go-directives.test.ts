/**
 * autofix-go-directives.test.ts
 *
 * AC2 – positive control: every protected Go directive comment is detected as exempt.
 * AC3 – property: autoFix never removes an exempt comment and never corrupts code.
 * AC4 – at least half of property iterations trigger removed>0.
 * AC5 – every corpus file is tracked by git (not swallowed by .gitignore).
 */


/**
 * Tests for the rfc manifest feature:
 *   - `rfc index <dir>` generates the manifest block in rfc.md
 *   - `rfc validate` detects stale manifests (freshness enforcement)
 *   - `rfc new` scaffolds a fresh manifest automatically
 *   - generateManifestBlock / extractManifestBlock round-trip
 *
 * Mutation tests included:
 *   M-M01: equality boundary — manifest comparison uses strict equality
 *   M-M02: staleness detection — a single changed token count triggers failure
 *   M-M03: missing-section detection — a new section file causes stale
 *   M-M04: schema gate — schema:1 RFCs are NOT freshness-checked
 */

import {
	execFileSync,
} from "node:child_process";
import {
	existsSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

import {
	generateManifestBlock,
	extractManifestBlock,
	writeManifest,
} from "../../hooks/lib/rfc-io.mjs";

const CLI = path.resolve(import.meta.dirname, "..", "..", "hooks", "rfc.mjs");

let projectDir: string;

beforeEach(() => {
	projectDir = mkdtempSync(path.join(tmpdir(), "gw-rfc-manifest-"));
});
afterEach(() => rmSync(projectDir, { recursive: true, force: true }));

function run(args: string[]): { code: number; stdout: string; stderr: string } {
	const env = { ...process.env, CLAUDE_PROJECT_DIR: projectDir };
	try {
		const stdout = execFileSync("node", [CLI, ...args], { env, encoding: "utf8" });
		return { code: 0, stdout, stderr: "" };
	} catch (e: any) {
		return { code: e.status ?? 1, stdout: e.stdout ?? "", stderr: e.stderr ?? "" };
	}
}

function rfcsDir() {
	return path.join(projectDir, ".groundwork", "rfcs");
}

function createRfc(slug = "test-feature"): string {
	const r = run(["new", slug]);
	expect(r.code).toBe(0);
	const match = r.stdout.match(/Created (.+)/);
	expect(match).toBeTruthy();
	return match![1].trim();
}

/**
 * Build a minimal schema-2 RFC directory with the given section files.
 * sections is a map of relative path under sections/ → file content.
 */
function makeRfc(slug: string, sections: Record<string, string>): string {
	const dir = path.join(rfcsDir(), `0001-${slug}`);
	mkdirSync(dir, { recursive: true });
	mkdirSync(path.join(dir, "sections"), { recursive: true });
	mkdirSync(path.join(dir, "notes"), { recursive: true });
	mkdirSync(path.join(dir, "reviews"), { recursive: true });
	writeFileSync(path.join(dir, "tasks.yaml"), "[]\n");
	for (const [rel, content] of Object.entries(sections)) {
		const full = path.join(dir, "sections", rel);
		mkdirSync(path.dirname(full), { recursive: true });
		writeFileSync(full, content);
	}
	// Write rfc.md with markers but no content (before index)
	const fm = [
		"---",
		"schema: 2",
		"uid: R-20260726-AAAAAA",
		"ordinal: 1",
		`slug: ${slug}`,
		`title: ${slug}`,
		"status: draft",
		"classification: tactical",
		`created: "2026-07-26T00:00:00.000Z"`,
		`updated: "2026-07-26T00:00:00.000Z"`,
		"accepted_at: null",
		"accepted_by: null",
		"supersedes: []",
		"superseded_by: null",
		"body_digest: null",
		"spec_delta: []",
		"---",
		"",
		"> Abstract: TODO",
		"",
		"<!-- rfc:manifest:begin — generated by `rfc index`; do not hand-edit -->",
		"<!-- rfc:manifest:end -->",
		"",
	].join("\n");
	writeFileSync(path.join(dir, "rfc.md"), fm);
	return dir;
}


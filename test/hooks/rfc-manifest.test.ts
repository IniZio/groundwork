describe("rfc index", () => {
	it("exits 2 when dir arg is missing", () => {
		const r = run(["index"]);
		expect(r.code).toBe(2);
	});

	it("exits 1 when rfc.md is missing", () => {
		const dir = mkdtempSync(path.join(tmpdir(), "gw-rfc-idx-"));
		try {
			const r = run(["index", dir]);
			expect(r.code).toBe(1);
		} finally {
			rmSync(dir, { recursive: true, force: true });
		}
	});

	it("exits 1 when sections/ is missing", () => {
		const rfcDir = createRfc("no-sections");
		rmSync(path.join(rfcDir, "sections"), { recursive: true, force: true });
		const r = run(["index", rfcDir]);
		expect(r.code).toBe(1);
	});

	it("exits 0 and writes the manifest", () => {
		const rfcDir = createRfc("demo");
		// Corrupt the manifest to make it stale
		const rfcMdPath = path.join(rfcDir, "rfc.md");
		const content = readFileSync(rfcMdPath, "utf8");
		const corrupted = content.replace(/<!-- rfc:manifest:end -->/, "<!-- corrupted -->\n<!-- rfc:manifest:end -->");
		writeFileSync(rfcMdPath, corrupted);

		const r = run(["index", rfcDir]);
		expect(r.code).toBe(0);
		expect(r.stdout).toContain("Manifest written");

		// Validate should now pass
		const v = run(["validate", rfcDir]);
		expect(v.code).toBe(0);
	});

	it("lists all section files reachable from the manifest", () => {
		const rfcDir = createRfc("full");
		const content = readFileSync(path.join(rfcDir, "rfc.md"), "utf8");
		// After rfc new, there should be 12 section rows
		const rows = content.split("\n").filter((l) => /^\| \d/.test(l));
		expect(rows.length).toBeGreaterThanOrEqual(12);
		// Each section file path should actually exist
		for (const row of rows) {
			const parts = row.split("|").map((s) => s.trim());
			const filePath = parts[3]; // 4th column
			if (!filePath || !filePath.startsWith("sections/")) continue;
			if (filePath.endsWith("/")) continue; // directory row — skip
			const abs = path.join(rfcDir, filePath);
			expect(existsSync(abs)).toBe(true);
		}
	});
});

// ---------------------------------------------------------------------------
// rfc validate — manifest freshness enforcement
// ---------------------------------------------------------------------------

describe("rfc validate manifest freshness", () => {
	// Primary acceptance criterion: a stale manifest fails validate.
	it("exits 1 when manifest is stale (hand-corrupted row)", () => {
		const rfcDir = createRfc("stale-test");
		const rfcMdPath = path.join(rfcDir, "rfc.md");
		const content = readFileSync(rfcMdPath, "utf8");
		// Corrupt one row by changing a token count
		const corrupted = content.replace(/\| (\d+) \| (.*?) \| (.*?) \| (\d+) \|/, (_m, n, t, f, tok) =>
			`| ${n} | ${t} | ${f} | ${parseInt(tok) + 9999} |`
		);
		writeFileSync(rfcMdPath, corrupted);
		const r = run(["validate", rfcDir]);
		expect(r.code).toBe(1);
		expect(r.stderr).toContain("manifest: stale");
	});

	// rfc index then validate exits 0 (standard round-trip)
	it("exits 0 after rfc index regenerates the manifest", () => {
		const rfcDir = createRfc("round-trip");
		// Corrupt then regenerate
		const rfcMdPath = path.join(rfcDir, "rfc.md");
		const content = readFileSync(rfcMdPath, "utf8");
		writeFileSync(rfcMdPath, content.replace(/\| \d+ \|.*\n/, ""));
		run(["index", rfcDir]);
		const r = run(["validate", rfcDir]);
		expect(r.code).toBe(0);
	});

	// A new section file without regenerating fails (M-M03)
	it("exits 1 when a new section file is added without regenerating (M-M03)", () => {
		const rfcDir = createRfc("new-section");
		// Add a 13th section file
		const sectionsDir = path.join(rfcDir, "sections");
		writeFileSync(path.join(sectionsDir, "13-extra.md"), "## 13. Extra\n\nExtra content\n");
		// Now validate without re-running rfc index
		const r = run(["validate", rfcDir]);
		expect(r.code).toBe(1);
		expect(r.stderr).toContain("manifest: stale");
	});

	// A section file is removed without regenerating fails
	it("exits 1 when a section file is removed without regenerating", () => {
		const rfcDir = createRfc("removed-section");
		// Remove one section file to make the manifest stale
		const sectionsDir = path.join(rfcDir, "sections");
		// Remove the last section (12-resolution.md) — leaves a numbering gap which is
		// also caught by layout validation, but manifest check runs too.
		rmSync(path.join(sectionsDir, "12-resolution.md"), { force: true });
		const r = run(["validate", rfcDir]);
		expect(r.code).toBe(1);
	});

	// schema: 1 RFC — manifest check must NOT run (M-M04)
	it("does not check manifest freshness for schema: 1 RFCs (M-M04)", () => {
		const rfcDir = createRfc("legacy");
		const rfcMdPath = path.join(rfcDir, "rfc.md");
		const content = readFileSync(rfcMdPath, "utf8");
		// Downgrade to schema: 1 and remove sections/ (schema 1 is lenient)
		const patched = content.replace(/^schema: 2$/m, "schema: 1");
		writeFileSync(rfcMdPath, patched);
		rmSync(path.join(rfcDir, "sections"), { recursive: true, force: true });
		const r = run(["validate", rfcDir]);
		expect(r.code).toBe(0);
	});

	// M-M01: equality boundary — a single extra space causes stale
	it("detects staleness on any byte difference — equality is strict (M-M01)", () => {
		const rfcDir = createRfc("equality-boundary");
		const rfcMdPath = path.join(rfcDir, "rfc.md");
		const content = readFileSync(rfcMdPath, "utf8");
		// Add a trailing space to one row (invisible but changes the block)
		const withSpace = content.replace(/\| 1 \|/, "| 1  |");
		writeFileSync(rfcMdPath, withSpace);
		const r = run(["validate", rfcDir]);
		expect(r.code).toBe(1);
		expect(r.stderr).toContain("manifest: stale");
	});

	// M-M02: changing only the token count triggers failure
	it("detects staleness when only a token count changes (M-M02)", () => {
		const rfcDir = createRfc("token-count-change");
		const rfcMdPath = path.join(rfcDir, "rfc.md");
		const content = readFileSync(rfcMdPath, "utf8");
		// Find a token count (digit at end of a manifest row) and change it by 1
		const changed = content.replace(/(\| sections\/\S+ \| )(\d+)( \|)/, (_m, pre, tok, post) =>
			`${pre}${parseInt(tok) + 1}${post}`
		);
		expect(changed).not.toBe(content); // Ensure we actually changed something
		writeFileSync(rfcMdPath, changed);
		const r = run(["validate", rfcDir]);
		expect(r.code).toBe(1);
		expect(r.stderr).toContain("manifest: stale");
	});
});

